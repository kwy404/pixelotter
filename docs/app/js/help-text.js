const build = (tools, extra, cmds) => {
  const out = { ...extra };
  for (const [id, text] of Object.entries(cmds)) out[`tip.cmd.${id}`] = text;
  for (const [id, [what, tip, hint]] of Object.entries(tools)) {
    out[`tip.tool.${id}`] = what;
    out[`tipx.tool.${id}`] = tip;
    out[`hint.tool.${id}`] = hint;
  }
  return out;
};

